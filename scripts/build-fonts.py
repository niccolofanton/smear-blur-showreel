"""Rebuild the vendored web fonts and 3D outlines: pip install fonttools brotli."""
import json
from pathlib import Path

from fontTools import subset
from fontTools.pens.basePen import BasePen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'public/fonts'
CHARS = 'SMEARBLU+'


class OutlinePen(BasePen):
    def __init__(self, glyphs, scale):
        super().__init__(glyphs)
        self.scale = scale
        self.commands = []

    def emit(self, command, *points):
        self.commands.append(command)
        self.commands.extend(str(round(v * self.scale, 3)) for p in points for v in p)

    def _moveTo(self, p):
        self.start = p
        self.emit('m', p)

    def _lineTo(self, p):
        self.emit('l', p)

    def _qCurveToOne(self, control, end):
        self.emit('q', end, control)

    def _curveToOne(self, a, b, end):
        self.emit('b', end, a, b)

    def _closePath(self):
        self.emit('l', self.start)

    def _endPath(self):
        pass


def webfont(font, name):
    options = subset.Options()
    options.layout_features = ['kern', 'liga', 'tnum', 'zero']
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=list(range(32, 256)) + [0x2013, 0x2014, 0x2192, 0x266A])
    sub.subset(font)
    font.flavor = 'woff2'
    font.save(OUT / name)


def drawn_plus(stem=187.5, arm=165, size=620, side=50):
    # The font's '+' is a light maths sign set low; the wordmark needs one at stem weight.
    x = [side, side + (size - stem) / 2, side + (size + stem) / 2, side + size]
    y = [500 - size / 2, 500 - arm / 2, 500 + arm / 2, 500 + size / 2]
    ring = [(1, 3), (2, 3), (2, 2), (3, 2), (3, 1), (2, 1), (2, 0), (1, 0), (1, 1), (0, 1), (0, 2), (1, 2), (1, 3)]
    tokens = [token for n, (i, j) in enumerate(ring) for token in ('l' if n else 'm', str(x[i]), str(y[j]))]
    advance = size + 2 * side
    return {'ha': advance, 'x_min': x[0], 'x_max': x[3], 'o': ' '.join(tokens)}, [advance, x[0], x[3]]


def typeface(font, name, chars):
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    scale = 1000 / font['OS/2'].sCapHeight
    outlines, metrics = {}, {}
    for char in chars:
        if char == '+':
            outlines[char], metrics[char] = drawn_plus()
            continue
        glyph = glyphs[cmap[ord(char)]]
        pen = OutlinePen(glyphs, scale)
        glyph.draw(pen)
        bounds = BoundsPen(glyphs)
        glyph.draw(bounds)
        left, bottom, right, top = [round(v * scale, 3) for v in bounds.bounds]
        advance = round(glyph.width * scale, 3)
        outlines[char] = {'ha': advance, 'x_min': left, 'x_max': right, 'o': ' '.join(pen.commands)}
        metrics[char] = [advance, left, right]
    font_data = {
        'familyName': name, 'resolution': 1000,
        'ascender': 1100, 'descender': -300,
        'boundingBox': {'xMin': 0, 'xMax': 1500, 'yMin': -300, 'yMax': 1100},
        'underlineThickness': 50, 'glyphs': outlines,
        'original_font_information': {'copyright': font['name'].getDebugName(0)},
    }
    (OUT / f'{name}.typeface.json').write_text(json.dumps(font_data, separators=(',', ':')) + '\n')
    return metrics


# Keeping the sources' timestamps makes a rebuild byte-identical when nothing changed.
display = instantiateVariableFont(TTFont(ROOT / 'assets/fonts/BigShoulders[opsz,wght].ttf', recalcTimestamp=False), {'wght': 900, 'opsz': 72})
metrics = typeface(display, 'big-shoulders-black', CHARS)
(ROOT / 'src/glyph-metrics.js').write_text(
    '// Generated by scripts/build-fonts.py; cap height = 1000.\n'
    + 'export const GLYPHS = ' + json.dumps(metrics, indent=2) + '\n')
webfont(display, 'big-shoulders-black.woff2')
mono = instantiateVariableFont(TTFont(ROOT / 'assets/fonts/AzeretMono[wght].ttf', recalcTimestamp=False), {'wght': 400})
webfont(mono, 'azeret-mono-regular.woff2')
print(json.dumps(metrics, indent=2))
